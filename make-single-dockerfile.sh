#!/usr/bin/env bash
# Generates Dockerfile.single: the same image definition as Dockerfile, but with the entrypoint
# script (container-build.sh) written INTO the Dockerfile, so that one file is the whole build
# context ("docker build --file Dockerfile.single" needs nothing else).
#
# Usage:  ./make-single-dockerfile.sh            (re-run after every change of Dockerfile or container-build.sh)
#         ./make-single-dockerfile.sh --check    (verify that Dockerfile.single is current and that the embedded
#                                                 script is byte-identical to container-build.sh; no Docker needed)
#
# Dockerfile.single is GENERATED. Edit Dockerfile or container-build.sh, never the generated file.
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SRC="$HERE/Dockerfile"
SCRIPT="$HERE/container-build.sh"
OUT="$HERE/Dockerfile.single"
DELIM=CTRLX_CONTAINER_BUILD_SCRIPT_END
COPY_LINE='COPY --chmod=755 container-build.sh /usr/local/bin/ctrlx-container-build'

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

[ -f "$SRC" ] && [ -f "$SCRIPT" ] || die "Dockerfile or container-build.sh not found next to this script"
[ "$(grep -cFx -- "$COPY_LINE" "$SRC")" = 1 ] || die "expected exactly one line '$COPY_LINE' in Dockerfile"
! grep -qFx -- "$DELIM" "$SCRIPT" || die "container-build.sh contains the heredoc delimiter line $DELIM"
[ -z "$(tail -c1 "$SCRIPT")" ] || die "container-build.sh must end with a newline"

generate() {
    local sum n
    sum=$(sha256sum "$SCRIPT" | cut -d' ' -f1)
    n=$(grep -nFx -- "$COPY_LINE" "$SRC" | cut -d: -f1)
    {
        printf '# GENERATED by make-single-dockerfile.sh from Dockerfile + container-build.sh. Do not edit.\n'
        printf '# container-build.sh sha256 %s (checked again during the image build).\n' "$sum"
        printf '# Build with this file alone:  docker build --tag <tag> --file Dockerfile.single <any folder containing it>\n#\n'
        head -n $((n - 1)) "$SRC"
        # Quoted delimiter: Docker must not expand ${...} or $(...) inside the script.
        printf 'COPY --chmod=755 <<'"'"'%s'"'"' /usr/local/bin/ctrlx-container-build\n' "$DELIM"
        cat "$SCRIPT"
        printf '%s\n' "$DELIM"
        printf 'RUN echo "%s  /usr/local/bin/ctrlx-container-build" | sha256sum --check --status\n' "$sum"
        tail -n +$((n + 1)) "$SRC"
    }
}

extract_embedded() { # prints the script as embedded in a Dockerfile.single
    awk -v d="$DELIM" '
        $0 ~ "^COPY --chmod=755 <<.?" d ".? /usr/local/bin/ctrlx-container-build$" {on=1; next}
        on && $0 == d {exit}
        on {print}' "$1"
}

case "${1:-}" in
    "")
        generate > "$OUT.tmp"
        mv "$OUT.tmp" "$OUT"
        printf 'wrote %s (%s lines)\n' "$OUT" "$(wc -l < "$OUT")"
        printf 'image tag for it: ctrlx-builder:single-%s\n' "$(sha256sum "$OUT" | cut -c1-12)"
        ;;
    --check)
        [ -f "$OUT" ] || die "Dockerfile.single does not exist; run without arguments first"
        generate | cmp -s - "$OUT" || die "Dockerfile.single is out of date; run ./make-single-dockerfile.sh"
        extract_embedded "$OUT" | cmp -s - "$SCRIPT" || die "embedded script differs from container-build.sh"
        ! grep -q '^COPY --chmod=755 container-build.sh' "$OUT" || die "Dockerfile.single still copies container-build.sh"
        printf 'ok: Dockerfile.single is current; embedded script is byte-identical to container-build.sh\n'
        ;;
    *) die "usage: $0 [--check]" ;;
esac
